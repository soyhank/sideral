const BY_ID = new Map(INDUSTRIES.map((i) => [i.id, i]));

export function getIndustry(id: IndustryId | string): IndustryDef {
  const ind = BY_ID.get(id as IndustryId);
  if (!ind) throw new Error(`Industria desconocida: ${id}`);
  return ind;
}

/** Venta trimestral base: la de una empresa promedio con su primera línea en Lima. */
export function baseRevenue(ind: IndustryDef): number {
  return ind.products[0].price * ind.products[0].units;
}

/** Tiene inventario físico que pasa de un trimestre a otro. */
export function hasInventory(ind: IndustryDef): boolean {
  return ind.model === "goods" || ind.model === "trade";
}
